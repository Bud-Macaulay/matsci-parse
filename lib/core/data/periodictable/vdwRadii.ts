/** Default van der Waals radii (Alvarez) in angstrom. */
export const vdwRadii = vdwRadiiAlvarez;

const tables: Readonly<
  Record<VdwRadiusSource, Readonly<Record<string, number | null>>>
> = {
  alvarez: vdwRadiiAlvarez,
  bondi: vdwRadiiBondi,
};

/** Look up an element's van der Waals radius in angstrom.
 * @param symbol - Element symbol (e.g. "Fe").
 * @param source - Radius set to use; defaults to Alvarez.
 * @returns The radius, null where untabulated, undefined if unknown symbol. */
export function getVdwRadius(
  symbol: string,
  source: VdwRadiusSource = "alvarez",
): number | null | undefined {
  return tables[source][symbol];
}
