/** User-facing options for {@link toPW}. Composed from schema types. */
export interface QEOptions {
  control?: QeControlOptions;
  system?: QeSystemOptions;
  electrons?: QeElectronsOptions;
  /** &IONS; only written (and only allowed) for relax, md, vc-relax, vc-md. */
  ions?: QeIonsOptions;
  /** &CELL; only written (and only allowed) for vc-relax, vc-md. */
  cell?: QeCellOptions;
  /**
   * K-points: a Monkhorst-Pack grid, a spacing (Å⁻¹, 2π included), or any
   * canonical {@link KPoints} (grids, explicit lists, band paths).
   */
  kpoints?:
    | { grid: [number, number, number]; shift?: [number, number, number] }
    | { kspacing: number }
    | KPoints;
  /** Pseudopotential file per species label, falling back to per element. */
  pseudo?: { pseudos?: Record<string, string> };
  /**
   * Species label per site, in `structure.sites` order. Defaults to each
   * site's `properties.kind` (set by fromPW for labels like "Fe1"), else the
   * element symbol. Use distinct labels to make sites of one element
   * separate QE species, e.g. ["Fe1", "Fe2", "O", "O"] for an antiferromagnet
   * with per-species `starting_magnetization`. Keep labels short: QE species
   * labels are at most 3 characters.
   */
  kinds?: readonly string[];
}

const QE_DEFAULTS = {
  control: {
    title: "Generated by matsci-parse",
    calculation: "scf",
    pseudo_dir: "./",
  },
  system: {
    ecutwfc: 30,
  },
  electrons: {
    conv_thr: 1e-6,
  },
  kpoints: { kspacing: 0.22 },
  pseudo: { pseudos: {} },
} satisfies Required<
  Pick<QEOptions, "control" | "system" | "electrons" | "kpoints" | "pseudo">
>;

