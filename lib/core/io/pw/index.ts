const RESERVED: Record<string, string[]> = {
  CONTROL: ["title"],
};

/** Serializes a Structure to a Quantum ESPRESSO PW input string. */
export function toPW(structure: Structure, options?: QEOptions): string {
  const ctrl = { ...QE_DEFAULTS.control, ...options?.control };
  const sys = { ...QE_DEFAULTS.system, ...options?.system };
  const { nat: _nat, ntyp: _ntyp, ibrav: _ibrav, ...sysOpts } = sys;
  const elec = { ...QE_DEFAULTS.electrons, ...options?.electrons };

  const calculation = ctrl.calculation ?? "scf";
  const readsIons = IONS_CALCULATIONS.has(calculation);
  const readsCell = CELL_CALCULATIONS.has(calculation);
  if (options?.ions && !readsIons) {
    throw new Error(
      `&IONS is only read for ${[...IONS_CALCULATIONS].join(", ")}, not calculation = '${calculation}'`,
    );
  }
  if (options?.cell && !readsCell) {
    throw new Error(
      `&CELL is only read for ${[...CELL_CALCULATIONS].join(", ")}, not calculation = '${calculation}'`,
    );
  }

  // --- derive card data from Structure ---
  const labels = siteLabels(structure, options?.kinds);
  const speciesOrder = pwSpeciesOrder(structure, options?.kinds);
  const species = buildAtomicSpecies(
    speciesOrder,
    labelElements(structure, labels),
    options?.pseudo?.pseudos,
  );
  const positions = buildAtomicPositions(structure, labels, speciesOrder);
  const cell = buildCellParameters(structure.lattice);
  const kpoints = buildKPoints(structure, options?.kpoints);

  // --- serialize ---
  const lines: string[] = [];

  lines.push(`title = '${ctrl.title}'`);
  lines.push("");
  writeNamelist(lines, "CONTROL", { ...ctrl, title: undefined });
  lines.push("");
  writeNamelist(lines, "SYSTEM", {
    ...sysOpts,
    nat: structure.sites.length,
    ntyp: speciesOrder.length,
    ibrav: 0,
  });
  lines.push("");
  writeNamelist(lines, "ELECTRONS", elec);
  lines.push("");
  if (readsIons) {
    writeNamelist(lines, "IONS", { ...options?.ions });
    lines.push("");
  }
  if (readsCell) {
    writeNamelist(lines, "CELL", { ...options?.cell });
    lines.push("");
  }

  lines.push(...serializeAtomicSpecies(species));
  lines.push("");
  lines.push(...kpoints);
  lines.push("");
  lines.push(...serializeCellParameters(cell));
  lines.push("");
  lines.push(
    ...serializeAtomicPositions(positions, structure.selectiveDynamics),
  );

  return lines.join("\n");
}


/** Calculations for which pw.x reads &IONS / &CELL. */
const IONS_CALCULATIONS = new Set(["relax", "md", "vc-relax", "vc-md"]);
const CELL_CALCULATIONS = new Set(["vc-relax", "vc-md"]);

/**
 * Species label per site: the given kinds, else each site's
 * `properties.kind` (as read by fromPW), else the element symbol.
 */
function siteLabels(
  structure: Structure,
  kinds?: readonly string[],
): readonly string[] {
  if (!kinds) {
    return structure.sites.map((site) =>
      typeof site.properties?.kind === "string"
        ? site.properties.kind
        : site.species.symbol,
    );
  }
  if (kinds.length !== structure.sites.length) {
    throw new Error(
      `kinds has ${kinds.length} labels but the structure has ${structure.sites.length} sites`,
    );
  }
  return kinds;
}

/** Element behind each label; a label may not stand for two elements. */
function labelElements(
  structure: Structure,
  labels: readonly string[],
): Map<string, string> {
  const elements = new Map<string, string>();
  structure.sites.forEach((site, i) => {
    const element = site.species.symbol;
    const seen = elements.get(labels[i]);
    if (seen !== undefined && seen !== element) {
      throw new Error(
        `Species label '${labels[i]}' is used for both ${seen} and ${element}`,
      );
    }
    elements.set(labels[i], element);
  });
  return elements;
}

/**
 * Order of the QE species (ATOMIC_SPECIES rows, and the index used by
 * per-species arrays such as `starting_magnetization(i)`): first appearance
 * of each label in `structure.sites`.
 */
export function pwSpeciesOrder(
  structure: Structure,
  kinds?: readonly string[],
): string[] {
  return [...new Set(siteLabels(structure, kinds))];
}

// ──────────────────────────────────────────────────────────────────────
//  Card builders — Structure + options → typed card data
// ──────────────────────────────────────────────────────────────────────

/** Build ATOMIC_SPECIES rows from species order + pseudopotential map. */
function buildAtomicSpecies(
  speciesOrder: string[],
  elements: Map<string, string>,
  pseudos?: Record<string, string>,
): AtomicSpeciesEntry[] {
  return speciesOrder.map((label) => {
    const element = elements.get(label) ?? label;
    const el = getElement(element);
    return {
      symbol: label,
      mass: el?.mass ?? 0,
      pseudo: pseudos?.[label] ?? pseudos?.[element] ?? `${element}.UPF`,
    };
  });
}

/** Build ATOMIC_POSITIONS rows, grouped by species label in `speciesOrder`. */
function buildAtomicPositions(
  structure: Structure,
  labels: readonly string[],
  speciesOrder: readonly string[],
): AtomicPositionEntry[] {
  const grouped = new Map<string, Site[]>(
    speciesOrder.map((label) => [label, []]),
  );
  structure.sites.forEach((site, i) => grouped.get(labels[i])!.push(site));

  const entries: AtomicPositionEntry[] = [];

  for (const label of speciesOrder) {
    for (const site of grouped.get(label) ?? []) {
      const entry: AtomicPositionEntry = {
        symbol: label,
        x: site.frac[0],
        y: site.frac[1],
        z: site.frac[2],
      };
      if (site.properties?.ifPos) {
        entry.ifPos = [
          site.properties.ifPos[0],
          site.properties.ifPos[1],
          site.properties.ifPos[2],
        ];
      }
      entries.push(entry);
    }
  }

  return entries;
}

/** Build CELL_PARAMETERS rows from Lattice. */
function buildCellParameters(
  lattice: Structure["lattice"],
): CellParameterEntry[] {
  const m = lattice.basis.data;
  return [
    [m[0], m[1], m[2]],
    [m[3], m[4], m[5]],
    [m[6], m[7], m[8]],
  ];
}

/** Build the K_POINTS card lines from options (with kspacing default). */
function buildKPoints(
  structure: Structure,
  kpoints?: QEOptions["kpoints"],
): string[] {
  if (kpoints && "kind" in kpoints) {
    return kpointsToPW(kpoints).split("\n");
  }
  const card: KPointsCard =
    kpoints && "grid" in kpoints
      ? { mode: "automatic", grid: kpoints.grid, shift: kpoints.shift ?? [0, 0, 0] }
      : {
          mode: "automatic",
          grid: kspacingToGrid(
            structure.lattice,
            kpoints?.kspacing ?? QE_DEFAULTS.kpoints.kspacing,
          ),
          shift: [0, 0, 0],
        };
  return serializeKPoints(card);
}

// ──────────────────────────────────────────────────────────────────────
//  Card serializers — typed card data → string lines
// ──────────────────────────────────────────────────────────────────────

function serializeAtomicSpecies(entries: AtomicSpeciesEntry[]): string[] {
  const lines = ["ATOMIC_SPECIES"];
  for (const e of entries) {
    lines.push(`${e.symbol}  ${e.mass}  ${e.pseudo}`);
  }
  return lines;
}

function serializeKPoints(card: KPointsCard): string[] {
  switch (card.mode) {
    case "gamma":
      return ["K_POINTS gamma"];
    case "automatic":
      return [
        "K_POINTS automatic",
        `${card.grid[0]}  ${card.grid[1]}  ${card.grid[2]}  ${card.shift[0]}  ${card.shift[1]}  ${card.shift[2]}`,
      ];
    default:
      // list / bands / covering — not used by toPW but handled for completeness
      throw new Error(`K_POINTS mode '${card.mode}' not yet supported in toPW`);
  }
}

function serializeCellParameters(
  entries: CellParameterEntry[],
  unit: "angstrom" | "bohr" | "alat" = "angstrom",
): string[] {
  const lines = [`CELL_PARAMETERS ${unit}`];
  for (const [a, b, c] of entries) {
    lines.push(`${a} ${b} ${c}`);
  }
  return lines;
}

function serializeAtomicPositions(
  entries: AtomicPositionEntry[],
  selectiveDynamics?: boolean,
  unit: "crystal" | "angstrom" | "bohr" | "alat" = "crystal",
): string[] {
  const lines = [`ATOMIC_POSITIONS ${unit}`];
  if (selectiveDynamics) {
    lines.push("Selective dynamics");
  }
  for (const e of entries) {
    let suffix = "";
    if (e.ifPos) {
      suffix = ` ${e.ifPos[0]} ${e.ifPos[1]} ${e.ifPos[2]}`;
    }
    lines.push(`${e.symbol} ${e.x} ${e.y} ${e.z}${suffix}`);
  }
  return lines;
}

// ──────────────────────────────────────────────────────────────────────
//  Namelist serializer — generic key → value
// ──────────────────────────────────────────────────────────────────────

function writeNamelist(
  lines: string[],
  name: string,
  params: Record<string, unknown>,
): void {
  const reserved = new Set(RESERVED[name] ?? []);
  const entries = Object.entries(params).filter(
    ([k, v]) => !reserved.has(k) && v !== undefined,
  );
  if (entries.length === 0) {
    lines.push(`&${name}`);
    lines.push("/");
    return;
  }
  lines.push(`&${name}`);
  for (const [key, value] of entries) {
    if (Array.isArray(value)) {
      // Fortran array syntax: key(1) = ..., key(2) = ...
      value.forEach((v, i) => {
        if (v === undefined || (typeof v === "number" && !Number.isFinite(v)))
          return;
        lines.push(`  ${key}(${i + 1}) = ${formatNamelistValue(v)}`);
      });
    } else if (typeof value === "string") {
      lines.push(`  ${key} = '${value}'`);
    } else if (typeof value === "boolean") {
      lines.push(`  ${key} = .${value ? "TRUE" : "FALSE"}.`);
    } else if (typeof value === "number" && !Number.isFinite(value)) {
      continue;
    } else {
      lines.push(`  ${key} = ${value}`);
    }
  }
  lines.push("/");
}

function formatNamelistValue(value: unknown): string {
  if (typeof value === "string") return `'${value}'`;
  if (typeof value === "boolean") return `.${value ? "TRUE" : "FALSE"}.`;
  return String(value);
}

