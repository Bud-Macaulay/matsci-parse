const BOHR_TO_ANGSTROM = 0.529177;

type AtomCoordMode = "crystal" | "angstrom" | "bohr" | "alat";

// ──────────────────────────────────────────────────────────────────────
//  Options — composed from schema types
// ──────────────────────────────────────────────────────────────────────

/** User-facing options for {@link toPW}. Composed from schema types. */
export interface QEOptions {
  control?: QeControlOptions;
  system?: QeSystemOptions;
  electrons?: QeElectronsOptions;
  kpoints?:
    | { grid: [number, number, number]; shift?: [number, number, number] }
    | { kspacing: number };
  pseudo?: { pseudos?: Record<string, string> };
}

const QE_DEFAULTS: Required<
  Pick<QEOptions, "control" | "system" | "electrons" | "kpoints" | "pseudo">
> = {
  control: {
    title: "Generated by matsci-parse",
    calculation: "scf",
    pseudo_dir: "./",
  },
  system: {
    ecutwfc: 30,
  },
  electrons: {
    conv_thr: 1e-6,
  },
  kpoints: { kspacing: 0.22 },
  pseudo: { pseudos: {} },
};

