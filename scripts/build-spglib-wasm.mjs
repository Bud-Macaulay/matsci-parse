#!/usr/bin/env node
// Build spglib (C) into a self-contained WASM module exposing a
// MoyoDataset-shaped interface (analyze_cell + niggli_reduce).
//
// Requires emscripten (emcc) on PATH or at $EMSDK_ROOT/upstream/emscripten/emcc.
// Output: lib/core/structure/operations/symmetry/spglib-wasm/{spglib_wasm.js,spglib_wasm.wasm}
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const spglibDir = join(root, "vendor", "spglib");
const outDir = join(
  root,
  "lib",
  "core",
  "structure",
  "operations",
  "symmetry",
  "spglib-wasm",
);
const genDir = join(root, "scripts", "spglib-wasm", "gen");

// version.h is generated by CMake from version.h.in in the spglib build.
// Pin the same values as the vendored v2.6.0 tag.
function writeVersionHeader() {
  mkdirSync(genDir, { recursive: true });
  const commit = execFileSync("git", ["-C", spglibDir, "rev-parse", "HEAD"])
    .toString()
    .trim();
  writeFileSync(
    join(genDir, "version.h"),
    `#ifndef __version_H__
#define __version_H__

#define SPGLIB_MAJOR_VERSION 2
#define SPGLIB_MINOR_VERSION 6
#define SPGLIB_MICRO_VERSION 0
#define SPGLIB_VERSION "2.6.0"
#define SPGLIB_VERSION_FULL "2.6.0"
#define SPGLIB_COMMIT "${commit}"

#endif
`,
  );
}

function findEmcc() {
  if (process.env.EMCC) return process.env.EMCC;
  if (process.env.EMSDK_ROOT) {
    const p = join(process.env.EMSDK_ROOT, "upstream", "emscripten", "emcc");
    if (existsSync(p)) return p;
  }
  return "emcc";
}

const srcs = [
  "arithmetic.c",
  "cell.c",
  "debug.c",
  "delaunay.c",
  "determination.c",
  "hall_symbol.c",
  "mathfunc.c",
  "msg_database.c",
  "niggli.c",
  "overlap.c",
  "pointgroup.c",
  "primitive.c",
  "refinement.c",
  "sitesym_database.c",
  "site_symmetry.c",
  "spacegroup.c",
  "spg_database.c",
  "spglib.c",
  "symmetry.c",
];

writeVersionHeader();
mkdirSync(outDir, { recursive: true });

const args = [
  "-O2",
  "-I",
  join(spglibDir, "include"),
  "-I",
  genDir,
  join(root, "scripts", "spglib-wasm", "wrapper.c"),
  ...srcs.map((s) => join(spglibDir, "src", s)),
  "-sEXPORTED_FUNCTIONS=" +
    JSON.stringify([
      "_malloc",
      "_free",
      "_spglib_analyze_cell",
      "_spglib_free_string",
      "_spglib_niggli_reduce",
    ]),
  "-sEXPORTED_RUNTIME_METHODS=" + JSON.stringify(["UTF8ToString", "getValue"]),
  "-sMODULARIZE=1",
  "-sEXPORT_NAME=createModule",
  "-sEXPORT_ES6=1",
  "-sALLOW_MEMORY_GROWTH=1",
  "-sENVIRONMENT=web",
  "-sFILESYSTEM=0",
  "--no-entry",
  "-o",
  join(outDir, "spglib_wasm.js"),
];

if (!existsSync(spglibDir)) {
  console.error(
    `spglib source not found at ${spglibDir}. Run: git submodule update --init vendor/spglib`,
  );
  process.exit(1);
}

console.log("Compiling spglib -> wasm ...");
execFileSync(findEmcc(), args, { stdio: "inherit" });
console.log(`Wrote ${join(outDir, "spglib_wasm.js")} and spglib_wasm.wasm`);
